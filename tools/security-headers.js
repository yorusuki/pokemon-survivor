'use strict';
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const ROOT = path.join(__dirname, '..');
// 只雜湊正式會部署的 HTML，不能將任意快取或上傳內容加入可執行白名單。
const directories = ['en', 'zh-TW', 'guia', 'pokedex', 'movimientos', 'objetos', 'legendarios', 'shinies', 'tipos', 'logros', 'novedades', 'apoyar', 'contacto'];
const files = [path.join(ROOT, 'index.html'), path.join(ROOT, 'oauth-result.html')];
function walk(dir) {
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, e.name);
    if (e.isDirectory()) walk(p); else if (e.name.endsWith('.html')) files.push(p);
  }
}
for (const d of directories) walk(path.join(ROOT, d));
const hashes = new Set();
for (const file of files) {
  const html = fs.readFileSync(file, 'utf8').replace(/\r\n?/g, '\n');
  for (const [, attrs, body] of html.matchAll(/<script\b([^>]*)>([\s\S]*?)<\/script\s*>/gi)) {
    if (/\bsrc\s*=/i.test(attrs) || /\btype\s*=\s*["']application\/ld\+json/i.test(attrs)) continue;
    if (body.trim()) hashes.add("'sha256-" + crypto.createHash('sha256').update(body).digest('base64') + "'");
  }
}
const csp = "default-src 'self'; script-src 'self' " + [...hashes].sort().join(' ')
  + "; style-src 'self' 'unsafe-inline'; img-src 'self' data: blob:; font-src 'self'; media-src 'self' data: blob:; connect-src 'self'; worker-src 'self' blob:; object-src 'none'; base-uri 'self'; form-action 'self'; frame-ancestors 'none'";
fs.writeFileSync(path.join(ROOT, 'deployment/security-headers.conf'), [
  '# Generated by tools/security-headers.js; regenerate after changing deployed HTML.',
  'add_header X-Content-Type-Options nosniff always;',
  'add_header Referrer-Policy same-origin always;',
  'add_header X-Frame-Options DENY always;',
  'add_header Cross-Origin-Resource-Policy same-origin always;',
  'add_header Permissions-Policy "camera=(), microphone=(), geolocation=()" always;',
  'add_header Content-Security-Policy "' + csp + '" always;', ''
].join('\n'));
console.log('Security headers generated: ' + files.length + ' HTML files, ' + hashes.size + ' inline script hashes');
